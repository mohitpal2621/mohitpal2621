ADVANCE = 6
LINE = 11


def runs_path(rows, char="#", dx=0, dy=0):
    """One SVG path that fills every `char` pixel, merging horizontal runs."""
    parts = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            if row[x] == char:
                s = x
                while x < len(row) and row[x] == char:
                    x += 1
                parts.append(f"M{s + dx} {y + dy}h{x - s}v1h-{x - s}z")
            else:
                x += 1
    return "".join(parts)


def sprite_paths(rows, key, attrs=""):
    """Paths for a multi-colour pixel sprite: one path per colour in `key` (char -> colour)."""
    out = []
    for ch, colour in key.items():
        d = runs_path(rows, ch)
        if d and colour:
            out.append(f'<path fill="{colour}" d="{d}"{attrs}/>')
    return "".join(out)


class Text:
    """Pixel text as <use> references to glyph paths; call defs() once all text is placed."""

    def __init__(self, prefix="g"):
        self.used = set()
        self.prefix = prefix

    def width(self, s, scale=1):
        return (len(s) * ADVANCE - 1) * scale

    def __call__(self, s, x, y, fill=None, scale=1, anchor="start", cls=None, extra=""):
        self.used.update(s)
        if anchor == "middle":
            x -= self.width(s, scale) / 2
        elif anchor == "end":
            x -= self.width(s, scale)
        uses = "".join(f'<use href="#{self.prefix}{ord(c)}" x="{i * ADVANCE}"/>'
                       for i, c in enumerate(s) if c != " " and c in FONT)
        paint = f' fill="{fill}"' if fill else ""
        klass = f' class="{cls}"' if cls else ""
        sc = f" scale({scale:g})" if scale != 1 else ""
        return f'<g{klass}{paint}{extra} transform="translate({x:g} {y:g}){sc}">{uses}</g>'

    def defs(self):
        return "".join(f'<path id="{self.prefix}{ord(c)}" d="{runs_path(FONT[c])}"/>'
                       for c in sorted(self.used) if c in FONT and c != " ")


def frame(x, y, w, h, fill, edge, shadow=None, step=2):
    """A pixel-art panel: square body with stepped (notched) corners, a 2px border and an optional drop shadow."""
    s = step
    def notched(x, y, w, h):
        return (f"M{x + s} {y}h{w - 2 * s}v{s}h{s}v{h - 2 * s}h{-s}v{s}h{-(w - 2 * s)}v{-s}h{-s}"
                f"v{-(h - 2 * s)}h{s}z")
    out = []
    if shadow:
        out.append(f'<path fill="{shadow}" d="{notched(x + 4, y + 4, w, h)}"/>')
    out.append(f'<path fill="{edge}" d="{notched(x, y, w, h)}"/>')
    out.append(f'<path fill="{fill}" d="{notched(x + s, y + s, w - 2 * s, h - 2 * s)}"/>')
    return "".join(out)


def svg(w, h, body, css="", defs="", title="", desc="", extra=""):
    t = f'<title id="t">{title}</title>' if title else ""
    d = f'<desc id="d">{desc}</desc>' if desc else ""
    labelled = ' aria-labelledby="t d"' if title and desc else (' aria-labelledby="t"' if title else "")
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" '
            f'shape-rendering="crispEdges" role="img"{labelled}{extra}>{t}{d}'
            + (f"<style>{css}</style>" if css else "") + (f"<defs>{defs}</defs>" if defs else "")
            + body + "</svg>" + NL)
